CREATE TABLE ordemservico.orcamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total NUMERIC(12, 2) NOT NULL
);

ALTER TABLE ordemservico.ordem_servico
    ADD COLUMN orcamento_id BIGINT REFERENCES ordemservico.orcamento (id);

CREATE TABLE ordemservico.item_orcamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id BIGINT NOT NULL REFERENCES ordemservico.orcamento (id),
    tipo VARCHAR(20) NOT NULL,
    descricao VARCHAR(200) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL
);
