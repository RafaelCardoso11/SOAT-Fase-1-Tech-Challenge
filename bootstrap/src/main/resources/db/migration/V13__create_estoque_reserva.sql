CREATE TABLE estoque.reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES estoque.item (id),
    os_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    situacao VARCHAR(10) NOT NULL CHECK (situacao IN ('ATIVA', 'LIBERADA', 'CONSUMIDA'))
);

CREATE UNIQUE INDEX uk_reserva_ativa_os_item ON estoque.reserva (os_id, item_id) WHERE situacao = 'ATIVA';

CREATE INDEX idx_reserva_os ON estoque.reserva (os_id);
