CREATE TABLE ordemservico.transicao_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL REFERENCES ordemservico.ordem_servico (id),
    status VARCHAR(30) NOT NULL,
    momento TIMESTAMP NOT NULL
);

CREATE INDEX idx_transicao_status_ordem ON ordemservico.transicao_status (ordem_servico_id);
