CREATE TABLE cadastro.cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento VARCHAR(14) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE cadastro.veiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(7) NOT NULL UNIQUE,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(60) NOT NULL,
    ano INTEGER NOT NULL,
    cliente_id BIGINT NOT NULL REFERENCES cadastro.cliente (id),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_veiculo_cliente_id ON cadastro.veiculo (cliente_id);

CREATE TABLE cadastro.servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    preco NUMERIC(12, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uk_servico_nome_lower ON cadastro.servico (lower(nome));
