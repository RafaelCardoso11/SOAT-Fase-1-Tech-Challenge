CREATE TABLE estoque.item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('PECA', 'INSUMO')),
    preco NUMERIC(12, 2) NOT NULL CHECK (preco >= 0),
    saldo INTEGER NOT NULL DEFAULT 0 CHECK (saldo >= 0),
    reservado INTEGER NOT NULL DEFAULT 0 CHECK (reservado >= 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_item_reservado_lte_saldo CHECK (reservado <= saldo)
);

CREATE UNIQUE INDEX uk_item_nome_lower ON estoque.item (lower(nome));
